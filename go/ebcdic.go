// buildInverse constructs an ASCII→EBCDIC lookup from an EBCDIC→ASCII table.
// Characters with no mapping default to 0x3F (EBCDIC '?').
func buildInverse(forward [256]byte) [256]byte {
	var inverse [256]byte
	for i := range inverse {
		inverse[i] = 0x3F // default: EBCDIC '?'
	}
	for eb := 0; eb < 256; eb++ {
		asc := forward[eb]
		if inverse[asc] == 0x3F {
			inverse[asc] = byte(eb)
		}
	}
	return inverse
}

// codePageRegistry holds all registered code pages keyed by IBM CP number.
var codePageRegistry = map[int]*codePage{}

func init() {
	// Register built-in code pages
	registerBuiltin(37, cp037ToASCII, "CP037 (US/Canada)")
	registerBuiltin(500, cp500ToASCII, "CP500 (International)")
}

func registerBuiltin(num int, forward [256]byte, name string) {
	codePageRegistry[num] = &codePage{
		toASCII:   forward,
		fromASCII: buildInverse(forward),
		name:      name,
	}
}

// getCodePage returns the code page for a given IBM CP number,
// falling back to CP037 if not found.
func getCodePage(cp int) *codePage {
	if page, ok := codePageRegistry[cp]; ok {
		return page
	}
	return codePageRegistry[37]
}

// ── Public EBCDIC API ──────────────────────────────────────────────────────

// EBCDICToASCII converts a byte slice from EBCDIC to an ASCII string.
// Non-printable characters are replaced with a space.
func EBCDICToASCII(data []byte, cp int) string {
	page := getCodePage(cp)
	out := make([]byte, len(data))
	for i, b := range data {
		a := page.toASCII[b]
		if a >= 0x20 && a < 0x7F {
			out[i] = a
		} else {
			out[i] = ' '
		}
	}
	return string(out)
}

// ASCIIToEBCDIC converts an ASCII string to an EBCDIC byte slice.
// Characters with no EBCDIC equivalent map to 0x3F (EBCDIC '?').
func ASCIIToEBCDIC(s string, cp int) []byte {
	page := getCodePage(cp)
	out := make([]byte, len(s))
	for i, c := range []byte(s) {
		out[i] = page.fromASCII[c]
	}
	return out
}

// ASCIIToEBCDICFixed converts an ASCII string to EBCDIC, padded or
// truncated to exactly n bytes. Useful for fixed-length 3270 input fields.
func ASCIIToEBCDICFixed(s string, n int, cp int) []byte {
	for len(s) < n {
		s += " "
	}
	return ASCIIToEBCDIC(s[:n], cp)
}

// RegisterCodePage registers a custom EBCDIC code page at runtime.
// forward must be a 256-byte EBCDIC→ASCII lookup table.
func RegisterCodePage(num int, forward [256]byte, name string) error {
	if num < 1 {
		return fmt.Errorf("invalid code page number: %d", num)
	}
	registerBuiltin(num, forward, name)
	return nil
}

// ListCodePages returns all registered code page numbers and names.
func ListCodePages() []struct {
	Number int
	Name   string
} {
	result := make([]struct {
		Number int
		Name   string
	}, 0, len(codePageRegistry))
	for num, page := range codePageRegistry {
		result = append(result, struct {
			Number int
			Name   string
		}{Number: num, Name: page.name})
	}
	return result
}
