package tn3270e

// ebcdic.go
// ─────────────────────────────────────────────────────────────────────────────
// EBCDIC ↔ ASCII conversion for TN3270E sessions.
//
// Background:
//   EBCDIC (Extended Binary Coded Decimal Interchange Code) is IBM's character
//   encoding used by all mainframe systems. It shares no common byte values
//   with ASCII for printable characters — 'A' is 0x41 in ASCII but 0xC1 in
//   EBCDIC CP037.
//
//   Code pages are regional variants. CP037 is US/Canadian standard.
//   European installations use CP273 (Germany), CP285 (UK), CP500
//   (International), etc.
//
// References:
//   IBM Character Data Representation Architecture (CDRA) — SC09-2190
// ─────────────────────────────────────────────────────────────────────────────

import "fmt"

// codePage holds forward (EBCDIC→ASCII) and inverse (ASCII→EBCDIC) tables.
type codePage struct {
	toASCII   [256]byte
	fromASCII [256]byte
	name      string
}

